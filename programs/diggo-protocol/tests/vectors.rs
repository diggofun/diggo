//! Golden vectors for the TypeScript mirrors (WS-G).
//!
//! Design 8.4 makes the chain authoritative: Rust generates the vectors, TypeScript asserts them,
//! and where the two disagree the Rust value wins because the chain is what pays. This file is the
//! Rust half. It writes tests/vectors/*.json, and when it is not asked to write it verifies that
//! what is committed is still what the program produces - so a change to a seed, a size, an error
//! code or the derivation fails here as well as in the TypeScript suite.
//!
//!   DIGGO_WRITE_VECTORS=1 cargo test -p diggo-protocol --test vectors   # regenerate
//!   cargo test -p diggo-protocol --test vectors                        # verify
//!
//! Three files are generated today. contract.json and epoch_seed.json come from the program crate
//! itself, so they are chain truth. tranche.json is the frozen starter-tranche rule expressed as an
//! independent integer implementation: it pins the simulator's model against the rule in
//! CONTRACTS.md's amendment while math/index.rs (WS-C) is still being written, and it is regenerated
//! from that file once it lands.

