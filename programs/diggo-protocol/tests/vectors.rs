/// The epoch-seed derivation of design 4.1: sha256(epoch_seed || owner || window_index as u16 LE).
/// This half is frozen - the expansion into occur, rarity and amount is WS-C's to write, and its
/// vectors belong beside these once math/index.rs and instructions/discovery.rs land.
#[test]
fn epoch_seed_vectors_match_the_derivation() {
    let cases: Vec<String> = (0..8)
        .map(|index| {
            let mut seed = [0u8; 32];
            for (position, byte) in seed.iter_mut().enumerate() {
                *byte = (index * 31 + position) as u8;
            }
            let mut owner = [0u8; 32];
            for (position, byte) in owner.iter_mut().enumerate() {
                *byte = (200 + index * 7 + position) as u8;
            }
            let window = (index * 3) as u16;
            let mut hasher = Sha256::new();
            hasher.update(seed);
            hasher.update(owner);
            hasher.update(window.to_le_bytes());
            let digest = hasher.finalize();
            format!(
                "{{\"epochSeedHex\": \"{}\", \"ownerHex\": \"{}\", \"windowIndex\": {}, \"digestHex\": \"{}\"}}",
                hex(&seed),
                hex(&owner),
                window,
                hex(&digest)
            )
        })
        .collect();
    let body = format!(
        "{{\n  \"derivation\": \"sha256(epoch_seed || owner || window_index_u16_le)\",\n  \"cases\": [\n    {}\n  ]\n}}",
        cases.join(",\n    ")
    );
    commit_family(
        "epoch_seed.json",
        body,
        "vectors.epochSeed.generated.ts",
        "EPOCH_SEED",
    );
}

/// The starter-tranche amendment of CONTRACTS.md, as integer arithmetic:
///
///   starter_take = min(block * STARTER_TRANCHE_BPS / BPS, block * starter_power / total_power)
///   bonded_take  = block - starter_take when there is bonded power, else 0
///   remainder    = block - starter_take - bonded_take, which stays in the Mining Reserve
///
/// The simulator (scripts/sim/v2rules.ts) asserts these same vectors, so its model cannot drift
/// from the rule the chain enforces. WS-C's math/index.rs is the other half of this pair.
#[test]
fn tranche_vectors_match_the_amendment() {
    let cases: Vec<String> = [
        (10_000u64, 0u64, 0u64),
        (10_000, 0, 1_000),
        (10_000, 1_000, 0),
        (10_000, 1_000, 1_000),
        (10_000, 1_000, 100_000),
        (10_000, 9_000, 1_000),
        (7_500, 1_400, 900),
        (1, 0, 1),
        (3, 1, 1),
        (999, 1, 1),
        (1_000_000, 1, 999_999),
        (7, 0, 5),
    ]
    .iter()
    .map(|(block, bonded, starter)| {
        let block = *block;
        let bonded = *bonded;
        let starter = *starter;
        let total = bonded + starter;
        let (starter_take, bonded_take) = if total == 0 {
            (0, 0)
        } else {
            let pro_rata = (block as u128 * starter as u128 / total as u128) as u64;
            let cap = (block as u128 * diggo_protocol::STARTER_TRANCHE_BPS as u128
                / diggo_protocol::BPS) as u64;
            let take = pro_rata.min(cap);
            if bonded == 0 {
                (take, 0)
            } else {
                (take, block - take)
            }
        };
        let remainder = block - starter_take - bonded_take;
        format!(
            "{{\"blockReward\": {block}, \"bondedPower\": {bonded}, \"starterPower\": {starter}, \"starterTake\": {starter_take}, \"bondedTake\": {bonded_take}, \"remainder\": {remainder}}}"
        )
    })
    .collect();
    let body = format!(
        "{{\n  \"rule\": \"starter tranche cap, CONTRACTS.md amendment\",\n  \"cases\": [\n    {}\n  ]\n}}",
        cases.join(",\n    ")
    );
    commit_family(
        "tranche.json",
        body,
        "vectors.tranche.generated.ts",
        "TRANCHE",
    );
}
