fn worktree_root() -> PathBuf {
    let mut path = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    path.pop();
    path.pop();
    path
}

fn vectors_dir() -> PathBuf {
    worktree_root().join("tests").join("vectors")
}

fn parity_dir() -> PathBuf {
    worktree_root().join("shared").join("parity")
}

/// The header every generated TypeScript vector module carries, so nobody edits one by hand.
const TS_HEADER: &str = "/* eslint-disable */\n// GENERATED by programs/diggo-protocol/tests/vectors.rs. Do not edit.\n// Regenerate with: DIGGO_WRITE_VECTORS=1 cargo test -p diggo-protocol --test vectors\n// Source of truth: the diggo_protocol crate itself (design 8.4: the chain is authoritative).\n\n";

/// Commits one vector family: the JSON a human reads and a tool consumes, and the TypeScript module
/// the parity harness imports. The harness has to import it rather than read the file, because
/// shared/** is type-checked by the worker project, which carries no @types/node and therefore has
/// no filesystem types - and a harness that cannot be type-checked is a harness nobody runs.
fn commit_family(json_name: &str, body: String, ts_name: &str, ts_export: &str) {
    let ts = format!("{TS_HEADER}export const {ts_export} = {body};\n");
    commit(json_name, format!("{body}\n"));
    commit_at(&parity_dir().join(ts_name), ts);
}

fn commit_at(path: &std::path::Path, contents: String) {
    if std::env::var("DIGGO_WRITE_VECTORS").is_ok() {
        fs::create_dir_all(path.parent().expect("parent")).expect("vectors dir");
        fs::write(path, &contents).expect("write vector file");
        println!("wrote {}", path.display());
        return;
    }
    let committed = fs::read_to_string(path).unwrap_or_else(|error| {
        panic!(
            "{} is missing or unreadable ({error}); regenerate with DIGGO_WRITE_VECTORS=1",
            path.display()
        )
    });
    assert_eq!(
        committed, contents,
        "{} is stale: the program no longer produces these vectors",
        path.display()
    );
}

/// Writes the file when DIGGO_WRITE_VECTORS is set, and otherwise requires it to be unchanged.
fn commit(name: &str, generated: String) {
    commit_at(&vectors_dir().join(name), generated);
}

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

fn json_string_array(values: &[String]) -> String {
    let quoted: Vec<String> = values.iter().map(|value| format!("\"{value}\"")).collect();
    format!("[{}]", quoted.join(", "))
}

