    #[test]
    fn tables_are_monotonic_and_start_at_the_starter_crew() {
        for i in 1..CURVE_TABLE_POWER_LEN {
            assert!(MINERS_POWER[i] > MINERS_POWER[i - 1]);
            assert!(UPGRADE_ORE_COST[0][i] > UPGRADE_ORE_COST[0][i - 1]);
        }
        assert_eq!(MINERS_POWER[0], 100);
        assert_eq!(DRILL_EFFICIENCY_BPS[0], 10_000);
        assert_eq!(FOREMAN_COST_BPS[0], 10_000);
        for level in 1..=MAX_CREW_LEVEL {
            assert!(DRILL_EFFICIENCY_BPS[(level - 1) as usize] >= 10_000);
            assert!(FOREMAN_COST_BPS[(level - 1) as usize] <= 10_000);
            assert!(FOREMAN_COST_BPS[(level - 1) as usize] >= 4_000);
        }
    }

    #[test]
    fn crew_power_is_monotonic_and_starts_at_one_hundred() {
        assert_eq!(crew_power(levels(1, 1)).unwrap(), 100);
        let mut previous = 0;
        for level in 1..=MAX_CREW_LEVEL {
            let power = crew_power(levels(level, 1)).unwrap();
            assert!(power > previous);
            previous = power;
            // Drills are a multiplier, so raising them never lowers power either.
            assert!(crew_power(levels(1, level)).unwrap() >= 100);
        }
    }

    #[test]
    fn crew_power_matches_the_published_curve() {
        // The values the frozen tables carry for the default config. shared/parity/player.json
        // republishes them from this side for WS-G, and shared/crew.test.ts asserts the same.
        assert_eq!(crew_power(levels(2, 1)).unwrap(), 153);
        assert_eq!(crew_power(levels(100, 1)).unwrap(), 1_737);
        assert_eq!(crew_power(levels(100, 100)).unwrap(), 2_257);
    }

    #[test]
    fn upgrade_cost_rises_with_level_and_falls_with_the_foreman() {
        assert_eq!(upgrade_ore_cost(0, 1, CREW_START_LEVEL).unwrap(), 80);
        assert!(upgrade_ore_cost(0, 1, MAX_CREW_LEVEL).unwrap() < upgrade_ore_cost(0, 1, CREW_START_LEVEL).unwrap());
        assert!(upgrade_ore_cost(0, 99, CREW_START_LEVEL).unwrap() > upgrade_ore_cost(0, 98, CREW_START_LEVEL).unwrap());
        // MAX_CREW_LEVEL itself is a real level with a real price; refusing to buy past it is
        // upgrade_crew's job (CrewAtMaxLevel), because a table with no entry would panic.
        assert!(upgrade_ore_cost(0, MAX_CREW_LEVEL, CREW_START_LEVEL).unwrap() > 0);
        assert!(upgrade_ore_cost(0, MAX_CREW_LEVEL + 1, CREW_START_LEVEL).is_err());
        assert!(upgrade_ore_cost(CREW_COMPONENTS as u8, 1, CREW_START_LEVEL).is_err());
    }

    #[test]
    fn maturity_ramp_is_the_designed_schedule() {
        assert_eq!(maturity_ramp_bps(0), 2_000);
        assert_eq!(maturity_ramp_bps(1), 4_000);
        assert_eq!(maturity_ramp_bps(2), 4_000);
        assert_eq!(maturity_ramp_bps(3), 7_000);
        assert_eq!(maturity_ramp_bps(6), 7_000);
        assert_eq!(maturity_ramp_bps(7), 10_000);
        assert_eq!(maturity_ramp_bps(10_000), 10_000);
        assert_eq!(power_maturity_bps(0, 0), 2_000);
        assert_eq!(power_maturity_bps(0, SLOTS_PER_DAY), 4_000);
        assert_eq!(power_maturity_bps(0, SLOTS_PER_DAY * 7), 10_000);
        // A clock that reads before the account existed is throttled, never credited.
        assert_eq!(power_maturity_bps(500, 100), 0);
    }

    #[test]
    fn power_is_crew_and_maturity_and_nothing_else() {
        let full = mining_power(levels(50, 50), 10_000).unwrap();
        assert_eq!(full, crew_power(levels(50, 50)).unwrap());
        // The retired starter efficiency cannot be reached from the derivation: the same crew at
        // full maturity is worth the whole table value, never the quarter it used to be worth to
        // an unbonded wallet.
        assert_ne!(full, full * STARTER_EFFICIENCY_BPS as u64 / BPS as u64);
        // Maturity is the only throttle left, it applies to the whole power, and nothing buys it
        // back.
        let young = mining_power(levels(50, 50), 2_000).unwrap();
        assert_eq!(young, full * 2_000 / 10_000);
        assert!(young < full);
    }

    #[test]
    fn mining_power_refuses_a_level_outside_the_tables() {
        assert!(mining_power(levels(0, 1), 10_000).is_err());
        assert!(mining_power(levels(MAX_CREW_LEVEL + 1, 1), 10_000).is_err());
        assert!(crew_power(levels(1, MAX_CREW_LEVEL + 1)).is_err());
    }
