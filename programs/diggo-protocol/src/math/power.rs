/// Bounded keeper power rule: never above ProtocolConfigV4.max_crew_power (itself clamped
/// by MAX_CREW_POWER_HARD_CAP), and never more than max_power_increase_bps plus the
/// always-allowed MIN_POWER_STEP above the previous value. Decreases are intentionally
/// unbounded so abuse handling can still reduce a player's power.
pub fn validate_power_update(
    protocol: &ProtocolConfigV4,
    previous_power: u64,
    new_power: u64,
) -> Result<()> {
    require!(
        new_power <= protocol.max_crew_power && new_power <= MAX_CREW_POWER_HARD_CAP,
        DiggoError::PowerOutOfRange
    );
    let allowed = previous_power
        .saturating_add(mul_bps(previous_power, protocol.max_power_increase_bps)?)
        .saturating_add(MIN_POWER_STEP);
    require!(new_power <= allowed, DiggoError::PowerIncreaseTooLarge);
    Ok(())
}

// ---- v2: the maturity ramp, the curve tables and the derived power -------------------------

/// Slots in one day at Solana's 400 ms target slot time. Power maturity is measured from the
/// PlayerAccount's creation **slot** (design section 5), because a slot is not something a
/// validator can nudge for profit the way it can nudge a timestamp. ORE maturity uses
/// `created_at` instead, where the extra precision is worth more than the residual.
pub const SLOTS_PER_DAY: u64 = 216_000;

/// Every crew branch starts at level 1 and no branch may pass MAX_CREW_LEVEL.
pub const CREW_START_LEVEL: u16 = 1;

/// Branch order, as the design names it: miners, drills, carts, foreman, storage. The
/// Foreman is the branch whose level discounts every other branch's upgrade price.
pub const CREW_MINERS_INDEX: usize = 0;
pub const CREW_DRILLS_INDEX: usize = 1;
pub const CREW_CARTS_INDEX: usize = 2;
pub const CREW_FOREMAN_INDEX: usize = 3;
pub const CREW_STORAGE_INDEX: usize = 4;

/// The maturity ramp as the (day, bps) schedule of design section 5: day 1 20%, day 3 40%,
/// day 7 70%, then 100%. A farm's wallets have to age before they bring a full share, and
/// nothing about that is a paywall. Power and ORE use the same schedule.
pub fn maturity_ramp_bps(days: u64) -> u16 {
    for (up_to_day, bps) in MATURITY_RAMP {
        if days < up_to_day {
            return bps;
        }
    }
    BPS as u16
}

/// Maturity of a PlayerAccount measured from its creation slot, in bps of full power.
pub fn power_maturity_bps(created_slot: u64, now_slot: u64) -> u16 {
    if now_slot < created_slot {
        return 0;
    }
    maturity_ramp_bps((now_slot - created_slot) / SLOTS_PER_DAY)
}

/// Table index of a crew level, or ConfigOutOfBounds when a caller hands over a level the
/// tables do not cover. Levels are only ever written by `upgrade_crew`, which refuses to pass
/// MAX_CREW_LEVEL, so this is a defensive bound rather than a reachable state.
pub fn level_index(level: u16) -> Result<usize> {
    require!(
        level >= CREW_START_LEVEL && level <= MAX_CREW_LEVEL,
        DiggoError::ConfigOutOfBounds
    );
    Ok((level - CREW_START_LEVEL) as usize)
}

