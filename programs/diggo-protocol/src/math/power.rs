//! math::power.rs - derived Mining Power. WS-A owns this file.
//!
//! Two things live here and nowhere else:
//!
//! 1. The **frozen curve tables** (design section 7). `crewPower()` is `pow(x, 0.62)` and
//!    `1 + gain * (1 - e^-k)` off-chain, and emulating those in integer math would drift from
//!    the values the client already publishes. Instead the numbers ship as program constant
//!    data: zero compute units to read, no rounding questions, and a golden-vector test that
//!    pins them against `shared/crew.ts` (shared/parity/player.json) so the two cannot
//!    silently diverge.
//! 2. **Derived power.** `assign_power` takes no power argument: a position's power is
//!    `mining_power(crew_levels, maturity)` computed in-program, so no caller can assert
//!    it, no keeper can push it, and nothing off-chain decides it. Money cannot reach it: the
//!    only input a player controls is `crew_levels`, and the only way to raise those is
//!    `upgrade_crew`, which is paid in ORE, and ORE is only ever earned by playing.

